"""Emit the release public keys as C, for the M7 verifier or for MCUboot.

A device trusts a short list of release keys: the primary, and optionally a
backup held by someone else (keys/README.md, "Backup key"). Two things embed
that list, and both are generated here from the same PEM files so they cannot
disagree:

--format m7 (default)
    The M7 application's own verifier (services/fw_release_sig.c), which checks
    the M4 and ESP32-C6 images -- neither is an MCUboot image. Each key is the
    raw uncompressed EC point (0x04 || X || Y, 65 bytes for P-256), which is
    what psa_import_key() takes for PSA_KEY_TYPE_ECC_PUBLIC_KEY. `imgtool
    getpub` only emits SubjectPublicKeyInfo DER, so the point is extracted here
    rather than sliced out at runtime with a magic offset.

--format mcuboot
    MCUboot's key table (bootutil_keys[] / bootutil_key_cnt), replacing the
    one-entry table boot/zephyr/keys.c builds (zephyr/patches.yml). Each key
    is SubjectPublicKeyInfo DER, the bytes imgtool hashes into the image's
    KEYHASH TLV, which is how MCUboot picks the key to verify with.

The script name predates the backup key and the ESP32-C6 path; it is invoked
by path from the build, so it keeps it.

Usage:
    gen_m4_pubkey.py --key primary.pem [--key backup.pem] --output keys.c
    gen_m4_pubkey.py --format mcuboot --key primary.pem --key backup.pem --output keys.c
"""

from __future__ import annotations

import argparse
import sys


def load_public(path: str):
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ec

    with open(path, "rb") as fh:
        blob = fh.read()
    try:
        pub = serialization.load_pem_private_key(blob, password=None).public_key()
    except (ValueError, TypeError):
        pub = serialization.load_pem_public_key(blob)

    if not isinstance(pub, ec.EllipticCurvePublicKey) or pub.curve.name != "secp256r1":
        sys.exit(
            f"gen_m4_pubkey: {path} is not an ECDSA P-256 key "
            "(the signing scheme is fixed at ECDSA-P256 -- see DFU_MASTER_PLAN §5)"
        )
    return pub


def c_bytes(data: bytes, indent: str) -> str:
    rows = []
    for i in range(0, len(data), 8):
        rows.append(indent + " ".join(f"0x{b:02x}," for b in data[i:i + 8]))
    return "\n".join(rows)


def emit_m7(points: list[bytes], paths: list[str]) -> str:
    entries = []
    for path, point in zip(paths, points):
        entries.append(f"\t/* {path} */\n\t{{\n{c_bytes(point, chr(9) * 2)}\n\t}},")
    return (
        "/* Generated by tools/build/gen_m4_pubkey.py -- do not edit.\n"
        " *\n"
        " * The release public keys the M7 application trusts, used by\n"
        " * services/fw_release_sig.c to verify M4 and ESP32-C6 images. A\n"
        " * signature from any one of them is accepted. Raw uncompressed EC\n"
        " * points (0x04 || X || Y) for psa_import_key().\n"
        " */\n"
        "\n"
        "#include <stdint.h>\n"
        "\n"
        f"const uint8_t hpi_fw_release_pubkeys[{len(points)}][65] = {{\n"
        + "\n".join(entries)
        + "\n};\n"
        f"const unsigned int hpi_fw_release_pubkey_count = {len(points)};\n"
    )


def emit_mcuboot(ders: list[bytes], paths: list[str]) -> str:
    arrays, table = [], []
    for i, (path, der) in enumerate(zip(paths, ders)):
        arrays.append(
            f"/* {path} */\n"
            f"static const unsigned char hpi_boot_key{i}[] = {{\n{c_bytes(der, chr(9))}\n}};\n"
            f"static const unsigned int hpi_boot_key{i}_len = {len(der)};\n"
        )
        table.append(f"\t{{ .key = hpi_boot_key{i}, .len = &hpi_boot_key{i}_len }},")
    return (
        "/* Generated by tools/build/gen_m4_pubkey.py --format mcuboot -- do not edit.\n"
        " *\n"
        " * MCUboot's public-key table, in place of the one-entry table that\n"
        " * boot/zephyr/keys.c builds (MCUBOOT_KEYS_EXTERNAL, zephyr/patches.yml).\n"
        " * SubjectPublicKeyInfo DER: bootutil_find_key() matches the SHA-256 of\n"
        " * these bytes against the image's KEYHASH TLV.\n"
        " */\n"
        "\n"
        "#include <mcuboot_config/mcuboot_config.h>\n"
        "#include <bootutil/sign_key.h>\n"
        "\n"
        "#if !defined(MCUBOOT_SIGN_EC256) || defined(MCUBOOT_HW_KEY) || defined(MCUBOOT_BUILTIN_KEY)\n"
        '#error "this key table is for ECDSA-P256 with keys built into MCUboot"\n'
        "#endif\n"
        "\n"
        + "\n".join(arrays)
        + "\nconst struct bootutil_key bootutil_keys[] = {\n"
        + "\n".join(table)
        + "\n};\n"
        f"const int bootutil_key_cnt = {len(ders)};\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--key", required=True, action="append",
                    help="PEM keypair or public key; repeat for each trusted key, "
                         "primary first")
    ap.add_argument("--format", choices=("m7", "mcuboot"), default="m7")
    ap.add_argument("--output", required=True, help="C file to write")
    args = ap.parse_args()

    try:
        from cryptography.hazmat.primitives import serialization
    except ImportError:
        sys.exit(
            "gen_m4_pubkey: python 'cryptography' not available. It ships with "
            "imgtool, which this build already needs -- activate the Zephyr venv."
        )

    pubs = [load_public(p) for p in args.key]
    ders = [p.public_bytes(serialization.Encoding.DER,
                           serialization.PublicFormat.SubjectPublicKeyInfo) for p in pubs]
    if len(set(ders)) != len(ders):
        sys.exit("gen_m4_pubkey: the same key was given twice -- a backup key "
                 "must be a different key, or it is no backup")

    if args.format == "m7":
        points = [p.public_bytes(serialization.Encoding.X962,
                                 serialization.PublicFormat.UncompressedPoint) for p in pubs]
        assert all(len(pt) == 65 for pt in points)
        text = emit_m7(points, args.key)
    else:
        text = emit_mcuboot(ders, args.key)

    with open(args.output, "w") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
