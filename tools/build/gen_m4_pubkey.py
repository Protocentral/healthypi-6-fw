"""Emit the M4-update verification public key as a C array.

The M4 is not an MCUboot image, so nothing in the bootloader verifies it — the
M7 application does, and it therefore needs its own copy of the public half of
the release signing key compiled in. This turns the PEM keypair used for MCUboot
signing into that copy, so both processors are anchored to ONE key and there is
no second thing to rotate.

The device wants the raw uncompressed EC point (0x04 || X || Y, 65 bytes for
P-256), which is what psa_import_key() takes for PSA_KEY_TYPE_ECC_PUBLIC_KEY.
`imgtool getpub` only emits SubjectPublicKeyInfo DER in every encoding it
offers, so the point is extracted here instead of being sliced out at runtime
with a magic offset.

Usage:
    gen_m4_pubkey.py --key keys/hp6_dev_ec256.pem --output m4fw_pubkey.c
"""

from __future__ import annotations

import argparse
import sys


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--key", required=True, help="PEM keypair (or public key)")
    ap.add_argument("--output", required=True, help="C file to write")
    args = ap.parse_args()

    try:
        from cryptography.hazmat.primitives import serialization
        from cryptography.hazmat.primitives.asymmetric import ec
    except ImportError:
        sys.exit(
            "gen_m4_pubkey: python 'cryptography' not available. It ships with "
            "imgtool, which this build already needs — activate the Zephyr venv."
        )

    with open(args.key, "rb") as fh:
        blob = fh.read()

    try:
        key = serialization.load_pem_private_key(blob, password=None)
        pub = key.public_key()
    except ValueError:
        pub = serialization.load_pem_public_key(blob)

    if not isinstance(pub, ec.EllipticCurvePublicKey) or pub.curve.name != "secp256r1":
        sys.exit(
            f"gen_m4_pubkey: {args.key} is not an ECDSA P-256 key "
            "(the signing scheme is fixed at ECDSA-P256 — see DFU_MASTER_PLAN §5)"
        )

    point = pub.public_bytes(
        encoding=serialization.Encoding.X962,
        format=serialization.PublicFormat.UncompressedPoint,
    )
    assert len(point) == 65, f"unexpected point length {len(point)}"

    rows = []
    for i in range(0, len(point), 8):
        rows.append("\t" + " ".join(f"0x{b:02x}," for b in point[i:i + 8]))

    body = "\n".join(rows)
    with open(args.output, "w") as fh:
        fh.write(
            "/* Generated by tools/build/gen_m4_pubkey.py -- do not edit.\n"
            " *\n"
            " * Public half of the release signing key, used by\n"
            " * services/m4_update_service.c to verify an uploaded M4 image.\n"
            " * Raw uncompressed EC point (0x04 || X || Y) for psa_import_key().\n"
            " */\n"
            "\n"
            "#include <stdint.h>\n"
            "\n"
            "const uint8_t hpi_m4fw_pubkey[65] = {\n"
            f"{body}\n"
            "};\n"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
