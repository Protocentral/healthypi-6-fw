# Regenerate pc_logo.c from art/pc_logo_long_2025.png (the ProtoCentral long
# logo: round mark + "PROTOCENTRAL" wordmark).
#
#     python convert_pc_logo.py      # needs Pillow + numpy (the Zephyr venv has both)
#
# The artwork is exactly two colours over an alpha channel -- the teal round
# mark (#015876, with the "PC" monogram cut out as transparency) and the grey
# wordmark (#6F6F6E). Like convert_logo.py this emits one LV_COLOR_FORMAT_A8
# mask per colour and LVGL paints them with image_recolor, so both colours
# live in the theme palette (pc_mark / pc_text) and follow DARK/LIGHT.
#
# Unlike the HealthyPi lockup, the logo is drawn at exactly one size, so the
# masks are rendered at that size and CROPPED to their own bounding boxes
# (offsets go in pc_logo.h). Nothing scales at runtime, so the two layers
# cannot drift out of registration, and cropping keeps it to a few KB.

import pathlib
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is required: python -m pip install pillow")

import numpy as np

HERE = pathlib.Path(__file__).parent
SRC = HERE / "art" / "pc_logo_long_2025.png"
OUT_C = HERE / "pc_logo.c"
OUT_H = HERE / "pc_logo.h"

MARK = (0x01, 0x58, 0x76)   # teal round mark
TEXT = (0x6F, 0x6F, 0x6E)   # grey wordmark

# Width on the panel, device pixels (boot splash). Change here and re-run.
TARGET_W = 240


def layers(path):
    im = Image.open(path).convert("RGBA")
    a = np.asarray(im).astype(np.int32)
    rgb, alpha = a[..., :3], a[..., 3]
    d_mark = np.abs(rgb - np.array(MARK)).sum(-1)
    d_text = np.abs(rgb - np.array(TEXT)).sum(-1)
    mark = np.where(d_mark <= d_text, alpha, 0).astype(np.uint8)
    text = np.where(d_mark > d_text, alpha, 0).astype(np.uint8)
    return im.size, mark, text


def scale(mask, w, h):
    return np.asarray(Image.fromarray(mask, mode="L").resize((w, h), Image.LANCZOS))


def crop(mask):
    ys, xs = np.nonzero(mask)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    return mask[y0:y1, x0:x1], int(x0), int(y0)


def emit(f, name, m):
    h, w = m.shape
    data = np.ascontiguousarray(m).tobytes()
    f.write(f"\nstatic const uint8_t {name}_map[] = {{\n")
    for i in range(0, len(data), 16):
        f.write("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
    f.write("};\n\n")
    f.write(f"const lv_image_dsc_t {name} = {{\n")
    f.write("\t.header = {\n")
    f.write("\t\t.magic = LV_IMAGE_HEADER_MAGIC,\n")
    f.write("\t\t.cf = LV_COLOR_FORMAT_A8,\n")
    f.write("\t\t.flags = 0,\n")
    f.write(f"\t\t.w = {w},\n\t\t.h = {h},\n\t\t.stride = {w},\n")
    f.write("\t\t.reserved_2 = 0,\n\t},\n")
    f.write(f"\t.data_size = sizeof({name}_map),\n\t.data = {name}_map,\n}};\n")
    return len(data)


def main():
    (sw, sh), mark, text = layers(SRC)
    w = TARGET_W
    h = round(sh * w / sw)
    mark, mx, my = crop(scale(mark, w, h))
    text, tx, ty = crop(scale(text, w, h))

    hdr = f"""/*
 * Copyright (c) 2026 Protocentral Electronics
 * SPDX-License-Identifier: MIT
 *
 * GENERATED by ui/assets/convert_pc_logo.py from art/pc_logo_long_2025.png.
 * Do not edit by hand -- re-run the script instead.
 *
 * The ProtoCentral long logo as two LV_COLOR_FORMAT_A8 masks, each cropped to
 * its own box on a {w}x{h} canvas. Draw with hpi_ui_pc_logo_create(), which
 * places and recolours them (palette fields pc_mark / pc_text).
 */
#ifndef PC_LOGO_H_
#define PC_LOGO_H_

#include <lvgl.h>

#define PC_LOGO_W       {w}
#define PC_LOGO_H       {h}
#define PC_LOGO_MARK_X  {mx}
#define PC_LOGO_MARK_Y  {my}
#define PC_LOGO_TEXT_X  {tx}
#define PC_LOGO_TEXT_Y  {ty}

extern const lv_image_dsc_t pc_logo_mark;   /* round mark, PC monogram cut out */
extern const lv_image_dsc_t pc_logo_text;   /* PROTOCENTRAL wordmark */

#endif /* PC_LOGO_H_ */
"""
    OUT_H.write_text(hdr)
    with OUT_C.open("w") as f:
        f.write("/*\n * Copyright (c) 2026 Protocentral Electronics\n")
        f.write(" * SPDX-License-Identifier: MIT\n *\n")
        f.write(" * GENERATED by ui/assets/convert_pc_logo.py -- do not edit by hand.\n */\n")
        f.write('#include "pc_logo.h"\n')
        total = emit(f, "pc_logo_mark", mark) + emit(f, "pc_logo_text", text)
    print(f"{OUT_C}: canvas {w}x{h}, mark {mark.shape[1]}x{mark.shape[0]}@({mx},{my}), "
          f"text {text.shape[1]}x{text.shape[0]}@({tx},{ty}), {total} B")


if __name__ == "__main__":
    main()
